"""Record a short demo of the chat UI against the fake Ollama server to docs/demo.gif."""
from __future__ import annotations

import os
import shutil
import socket
import subprocess
import sys
import tempfile
import time
from pathlib import Path
from typing import List

import httpx
from playwright.sync_api import sync_playwright

ROOT = Path(__file__).resolve().parent.parent
DOCS_DIR = ROOT / "docs"
OUT_GIF = DOCS_DIR / "demo.gif"


def find_free_port() -> int:
    """Find an available TCP port on localhost."""
    with socket.socket(socket.AF_INET, socket.SOCK_STREAM) as s:
        s.bind(("127.0.0.1", 0))
        return int(s.getsockname()[1])


def wait_for_url(url: str, timeout_sec: float = 30.0) -> bool:
    """Poll an HTTP URL until it returns 200 OK or timeout expires."""
    start = time.time()
    while time.time() - start < timeout_sec:
        try:
            r = httpx.get(url, timeout=1.0)
            if r.status_code == 200:
                return True
        except Exception:
            pass
        time.sleep(0.3)
    return False


def terminate_process(proc: subprocess.Popen[bytes] | None) -> None:
    """Safely terminate a subprocess, falling back to kill if unresponsive."""
    if proc is None or proc.poll() is not None:
        return
    try:
        proc.terminate()
        proc.wait(timeout=5)
    except (subprocess.TimeoutExpired, Exception):
        try:
            proc.kill()
            proc.wait(timeout=3)
        except Exception:
            pass


def record_chat(app_port: int, video_dir: Path) -> Path:
    """Drive Playwright to interact with the chat UI and record video."""
    messages_to_send: List[str] = [
        "hey",
        "i have an interview tomorrow",
        "thanks",
    ]

    with sync_playwright() as p:
        browser = p.chromium.launch(headless=True)
        context = browser.new_context(
            record_video_dir=str(video_dir),
            viewport={"width": 390, "height": 760},
        )
        page = context.new_page()

        page.goto(f"http://127.0.0.1:{app_port}", wait_until="networkidle")

        # Give the chat UI an initial moment to stabilize
        page.wait_for_timeout(1000)

        input_box = page.get_by_placeholder("Message")
        input_box.wait_for(state="visible", timeout=10000)

        for msg in messages_to_send:
            input_box.click()
            # Type with a realistic slight delay between keystrokes
            input_box.type(msg, delay=80)
            page.wait_for_timeout(300)

            # Click send or press Enter
            send_btn = page.locator("button.send-btn[aria-label='Send']")
            if send_btn.is_visible():
                send_btn.click()
            else:
                input_box.press("Enter")

            # Wait for assistant response to finish typing/streaming
            # In InputBar.jsx, send button has disabled={disabled} where disabled is `sending`
            # When response finishes, `sending` becomes false, and send_btn / input becomes enabled again.
            page.wait_for_selector(".bubble.her", state="visible", timeout=15000)
            page.wait_for_function(
                "() => !document.querySelector('input.text-input')?.disabled",
                timeout=20000,
            )
            # Extra pause to let viewer read the reply
            page.wait_for_timeout(1500)

        # Brief trailing pause before finishing
        page.wait_for_timeout(1500)

        # Saving video requires closing the context / page
        page.close()
        context.close()
        browser.close()

    # Find the recorded .webm file
    webm_files = list(video_dir.glob("*.webm"))
    if not webm_files:
        raise RuntimeError("No .webm video was generated by Playwright.")
    return webm_files[0]


def convert_webm_to_gif(webm_path: Path, output_gif: Path, temp_dir: Path) -> None:
    """Convert .webm recording to optimized GIF using ffmpeg palettegen & paletteuse."""
    output_gif.parent.mkdir(parents=True, exist_ok=True)
    palette_path = temp_dir / "palette.png"

    # Pass 1: palettegen
    cmd_palette = [
        "ffmpeg",
        "-y",
        "-i",
        str(webm_path),
        "-vf",
        "fps=12,scale=390:-1:flags=lanczos,palettegen",
        str(palette_path),
    ]
    subprocess.run(cmd_palette, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)

    # Pass 2: paletteuse
    cmd_gif = [
        "ffmpeg",
        "-y",
        "-i",
        str(webm_path),
        "-i",
        str(palette_path),
        "-lavfi",
        "fps=12,scale=390:-1:flags=lanczos [x]; [x][1:v] paletteuse",
        str(output_gif),
    ]
    subprocess.run(cmd_gif, check=True, stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)


def main() -> int:
    temp_dir_obj = tempfile.TemporaryDirectory()
    temp_dir = Path(temp_dir_obj.name)

    fake_ollama_proc: subprocess.Popen[bytes] | None = None
    uvicorn_proc: subprocess.Popen[bytes] | None = None

    try:
        ollama_port = find_free_port()
        app_port = find_free_port()

        # Step 1: Start fake Ollama server
        ollama_cmd = [
            sys.executable,
            str(ROOT / "tools" / "fake_ollama.py"),
            "--host",
            "127.0.0.1",
            "--port",
            str(ollama_port),
        ]
        fake_ollama_proc = subprocess.Popen(ollama_cmd)

        ollama_health_url = f"http://127.0.0.1:{ollama_port}/api/tags"
        if not wait_for_url(ollama_health_url, timeout_sec=15.0):
            raise RuntimeError(f"Fake Ollama failed to start on port {ollama_port}")

        # Step 2: Start uvicorn app with temporary environment
        env = os.environ.copy()
        env["OLLAMA_BASE_URL"] = f"http://127.0.0.1:{ollama_port}"
        env["COMPANION_DB_PATH"] = str(temp_dir / "test_companion.db")
        env["CHROMA_PATH"] = str(temp_dir / "test_chroma_db")
        env["COMPANION_AUTH_TOKEN"] = ""  # Localhost is exempt anyway

        uvicorn_cmd = [
            sys.executable,
            "-m",
            "uvicorn",
            "app.main:app",
            "--host",
            "127.0.0.1",
            "--port",
            str(app_port),
            "--log-level",
            "warning",
        ]
        uvicorn_proc = subprocess.Popen(uvicorn_cmd, env=env)

        app_health_url = f"http://127.0.0.1:{app_port}/health"
        if not wait_for_url(app_health_url, timeout_sec=30.0):
            raise RuntimeError(f"App server failed to start on port {app_port}")

        # Step 3: Record UI interactions with Playwright
        video_dir = temp_dir / "video"
        video_dir.mkdir(parents=True, exist_ok=True)

        webm_file = record_chat(app_port, video_dir)

        # Step 4: Convert WebM to GIF using ffmpeg
        convert_webm_to_gif(webm_file, OUT_GIF, temp_dir)

        # Verify output GIF
        if not OUT_GIF.exists():
            raise RuntimeError(f"Output GIF was not created at {OUT_GIF}")

        size_mb = OUT_GIF.stat().st_size / (1024 * 1024)
        print(f"Recorded demo GIF successfully: {OUT_GIF} ({size_mb:.2f} MB)")

    finally:
        # Stop servers and clean up temp files
        terminate_process(uvicorn_proc)
        terminate_process(fake_ollama_proc)
        try:
            temp_dir_obj.cleanup()
        except Exception:
            shutil.rmtree(temp_dir, ignore_errors=True)

    return 0


if __name__ == "__main__":
    sys.exit(main())
